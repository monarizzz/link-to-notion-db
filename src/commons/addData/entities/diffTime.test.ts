import { describe, expect, it } from "vitest";

import { diffTime } from "./diffTime";

describe("diffTime", () => {
  it("通常の差分を返す（1時間30分）", () => {
    expect(diffTime("2024-01-01T09:00:00", "2024-01-01T10:30:00")).toBe(
      "1時間 30分",
    );
  });

  it("1時間ちょうどの場合", () => {
    expect(diffTime("2024-01-01T09:00:00", "2024-01-01T10:00:00")).toBe(
      "1時間 0分",
    );
  });

  it("1時間未満の場合（30分）", () => {
    expect(diffTime("2024-01-01T09:00:00", "2024-01-01T09:30:00")).toBe(
      "0時間 30分",
    );
  });

  it("end == start の場合は '-' を返す", () => {
    expect(diffTime("2024-01-01T09:00:00", "2024-01-01T09:00:00")).toBe("-");
  });

  it("end < start の場合は '-' を返す", () => {
    expect(diffTime("2024-01-01T10:00:00", "2024-01-01T09:00:00")).toBe("-");
  });

  it("1分未満の場合は '-' を返す", () => {
    expect(diffTime("2024-01-01T09:00:00", "2024-01-01T09:00:59")).toBe("-");
  });

  it("日付を跨ぐ場合（23:00 → 翌01:30）", () => {
    expect(diffTime("2024-01-01T23:00:00", "2024-01-02T01:30:00")).toBe(
      "2時間 30分",
    );
  });

  it("時刻のみの文字列の場合", () => {
    expect(diffTime("09:00", "10:30")).toBe("-");
  });

  it("start が日付なし・end が日付ありの場合", () => {
    expect(diffTime("09:00", "2024-01-01T10:30:00")).toBe("-");
  });
});
